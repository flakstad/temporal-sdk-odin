use anyhow::{Context, Result, bail};
use prost::Message;
use prost_descriptor_types::{
    DescriptorProto, EnumDescriptorProto, FieldDescriptorProto, FileDescriptorSet,
    field_descriptor_proto::{Label, Type},
};
use std::{
    collections::{BTreeMap, BTreeSet},
    env, fs,
    path::PathBuf,
};

#[derive(Clone)]
struct MessageInfo {
    descriptor: DescriptorProto,
}

#[derive(Clone)]
struct EnumInfo {
    descriptor: EnumDescriptorProto,
}

#[derive(Default)]
struct Schema {
    messages: BTreeMap<String, MessageInfo>,
    enums: BTreeMap<String, EnumInfo>,
}

fn main() -> Result<()> {
    let mut args = env::args_os().skip(1);
    let descriptor_path = PathBuf::from(args.next().context("missing descriptor-set path")?);
    let output_path = PathBuf::from(args.next().context("missing output path")?);
    let roots = args
        .map(|value| value.to_string_lossy().into_owned())
        .collect::<Vec<_>>();
    if roots.is_empty() {
        bail!("at least one fully-qualified root message is required");
    }

    let descriptor_bytes = fs::read(&descriptor_path)
        .with_context(|| format!("read {}", descriptor_path.display()))?;
    let descriptor_set = FileDescriptorSet::decode(descriptor_bytes.as_slice())
        .context("decode FileDescriptorSet")?;
    let schema = index_schema(&descriptor_set);
    let reachable = reachable_messages(&schema, &roots)?;
    let generated = generate(&schema, &reachable, &roots)?;
    fs::write(&output_path, generated)
        .with_context(|| format!("write {}", output_path.display()))?;
    Ok(())
}

fn index_schema(descriptor_set: &FileDescriptorSet) -> Schema {
    let mut schema = Schema::default();
    for file in &descriptor_set.file {
        let package = file.package.as_deref().unwrap_or_default();
        for message in &file.message_type {
            index_message(&mut schema, package, message);
        }
        for enumeration in &file.enum_type {
            let full_name = qualify(package, enumeration.name.as_deref().unwrap_or_default());
            schema.enums.insert(
                full_name,
                EnumInfo {
                    descriptor: enumeration.clone(),
                },
            );
        }
    }
    schema
}

fn index_message(schema: &mut Schema, prefix: &str, message: &DescriptorProto) {
    let full_name = qualify(prefix, message.name.as_deref().unwrap_or_default());
    schema.messages.insert(
        full_name.clone(),
        MessageInfo {
            descriptor: message.clone(),
        },
    );
    for nested in &message.nested_type {
        index_message(schema, &full_name, nested);
    }
    for enumeration in &message.enum_type {
        let enum_name = qualify(&full_name, enumeration.name.as_deref().unwrap_or_default());
        schema.enums.insert(
            enum_name,
            EnumInfo {
                descriptor: enumeration.clone(),
            },
        );
    }
}

fn qualify(prefix: &str, name: &str) -> String {
    if prefix.is_empty() {
        name.to_owned()
    } else {
        format!("{prefix}.{name}")
    }
}

fn normalized_type_name(field: &FieldDescriptorProto) -> Option<String> {
    field
        .type_name
        .as_deref()
        .map(|name| name.trim_start_matches('.').to_owned())
}

fn reachable_messages(schema: &Schema, roots: &[String]) -> Result<BTreeSet<String>> {
    let mut reachable = BTreeSet::new();
    let mut pending = roots.to_vec();
    while let Some(name) = pending.pop() {
        if !reachable.insert(name.clone()) {
            continue;
        }
        let message = schema
            .messages
            .get(&name)
            .with_context(|| format!("root or referenced message {name} not found"))?;
        for field in &message.descriptor.field {
            if field.r#type() == Type::Message {
                let referenced = normalized_type_name(field)
                    .with_context(|| format!("message field in {name} has no type_name"))?;
                pending.push(referenced);
            }
        }
    }
    Ok(reachable)
}

fn generate(schema: &Schema, reachable: &BTreeSet<String>, roots: &[String]) -> Result<String> {
    let mut output = String::new();
    output.push_str("// Code generated by native/odin-proto-gen. DO NOT EDIT.\n");
    output.push_str("// Source: pinned sdk-core protobuf descriptors.\n");
    output.push_str(&format!("// Roots: {}\n\n", roots.join(", ")));
    output.push_str("package proto\n\n");
    output.push_str("import protobuf \"../../protobuf\"\n\n");

    let reachable_enums = reachable_enums(schema, reachable)?;
    for name in &reachable_enums {
        emit_enum(&mut output, name, &schema.enums[name].descriptor);
    }
    for name in reachable {
        emit_oneof_types(&mut output, name, &schema.messages[name].descriptor, schema)?;
    }
    for name in reachable {
        emit_message_type(&mut output, name, &schema.messages[name].descriptor, schema)?;
    }
    for name in reachable {
        emit_decoder(&mut output, name, &schema.messages[name].descriptor, schema)?;
    }
    for name in reachable {
        emit_encoder(&mut output, name, &schema.messages[name].descriptor, schema)?;
    }
    while output.ends_with("\n\n") {
        output.pop();
    }
    Ok(output)
}

fn reachable_enums(schema: &Schema, reachable: &BTreeSet<String>) -> Result<BTreeSet<String>> {
    let mut result = BTreeSet::new();
    for message_name in reachable {
        for field in &schema.messages[message_name].descriptor.field {
            if field.r#type() == Type::Enum {
                let name = normalized_type_name(field)
                    .with_context(|| format!("enum field in {message_name} has no type_name"))?;
                if !schema.enums.contains_key(&name) {
                    bail!("referenced enum {name} not found");
                }
                result.insert(name);
            }
        }
    }
    Ok(result)
}

fn odin_type_name(full_name: &str) -> String {
    full_name
        .split('.')
        .map(pascal_identifier)
        .collect::<Vec<_>>()
        .join("_")
}

fn pascal_identifier(value: &str) -> String {
    let mut result = String::new();
    let mut uppercase = true;
    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            if uppercase {
                result.extend(character.to_uppercase());
                uppercase = false;
            } else {
                result.push(character);
            }
        } else {
            uppercase = true;
            result.push('_');
        }
    }
    if result.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        result.insert(0, '_');
    }
    result
}

fn odin_identifier(value: &str) -> String {
    let mut result = value
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || character == '_' {
                character
            } else {
                '_'
            }
        })
        .collect::<String>();
    if result.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        result.insert(0, '_');
    }
    const RESERVED: &[&str] = &[
        "package",
        "import",
        "foreign",
        "proc",
        "struct",
        "union",
        "enum",
        "map",
        "dynamic",
        "distinct",
        "using",
        "if",
        "else",
        "when",
        "for",
        "switch",
        "case",
        "defer",
        "return",
        "context",
        "typeid",
        "auto_cast",
    ];
    if RESERVED.contains(&result.as_str()) {
        result.push('_');
    }
    result
}

fn field_base_type(field: &FieldDescriptorProto) -> Result<String> {
    let result = match field.r#type() {
        Type::Double => "f64".to_owned(),
        Type::Float => "f32".to_owned(),
        Type::Int64 | Type::Sint64 | Type::Sfixed64 => "i64".to_owned(),
        Type::Uint64 | Type::Fixed64 => "u64".to_owned(),
        Type::Int32 | Type::Sint32 | Type::Sfixed32 => "i32".to_owned(),
        Type::Uint32 | Type::Fixed32 => "u32".to_owned(),
        Type::Bool => "bool".to_owned(),
        Type::String => "string".to_owned(),
        Type::Bytes => "[]u8".to_owned(),
        Type::Message | Type::Enum => odin_type_name(
            normalized_type_name(field)
                .context("message/enum field is missing type_name")?
                .as_str(),
        ),
        Type::Group => bail!("deprecated protobuf groups are unsupported"),
    };
    Ok(result)
}

fn field_storage_type(field: &FieldDescriptorProto, in_oneof: bool) -> Result<String> {
    let base = field_base_type(field)?;
    if field.label() == Label::Repeated && !in_oneof {
        return Ok(format!("[dynamic]{base}"));
    }
    if field.r#type() == Type::Message {
        return Ok(format!("^{base}"));
    }
    Ok(base)
}

fn emit_enum(output: &mut String, full_name: &str, enumeration: &EnumDescriptorProto) {
    output.push_str(&format!("{} :: enum i32 {{\n", odin_type_name(full_name)));
    for value in &enumeration.value {
        let name = pascal_identifier(value.name.as_deref().unwrap_or("Unspecified"));
        let number = value.number.unwrap_or_default();
        output.push_str(&format!("\t{name} = {number},\n"));
    }
    output.push_str("}\n\n");
}

fn oneof_fields(
    message: &DescriptorProto,
    oneof_index: usize,
) -> impl Iterator<Item = &FieldDescriptorProto> {
    message
        .field
        .iter()
        .filter(move |field| field.oneof_index == Some(oneof_index as i32))
}

fn emit_oneof_types(
    output: &mut String,
    full_name: &str,
    message: &DescriptorProto,
    _schema: &Schema,
) -> Result<()> {
    let message_type = odin_type_name(full_name);
    for (index, declaration) in message.oneof_decl.iter().enumerate() {
        let oneof_name = pascal_identifier(declaration.name.as_deref().unwrap_or("Choice"));
        let union_name = format!("{message_type}_{oneof_name}");
        let fields = oneof_fields(message, index).collect::<Vec<_>>();
        for field in &fields {
            let wrapper = format!(
                "{union_name}_{}",
                pascal_identifier(field.name.as_deref().unwrap_or("Value"))
            );
            output.push_str(&format!(
                "{wrapper} :: struct {{ value: {} }}\n",
                field_storage_type(field, true)?
            ));
        }
        output.push_str(&format!("{union_name} :: union {{\n"));
        for field in &fields {
            output.push_str(&format!(
                "\t{union_name}_{},\n",
                pascal_identifier(field.name.as_deref().unwrap_or("Value"))
            ));
        }
        output.push_str("}\n\n");
    }
    Ok(())
}

fn emit_message_type(
    output: &mut String,
    full_name: &str,
    message: &DescriptorProto,
    _schema: &Schema,
) -> Result<()> {
    let message_type = odin_type_name(full_name);
    output.push_str(&format!("{message_type} :: struct {{\n"));
    for field in message
        .field
        .iter()
        .filter(|field| field.oneof_index.is_none())
    {
        output.push_str(&format!(
            "\t{}: {},\n",
            odin_identifier(field.name.as_deref().unwrap_or("field")),
            field_storage_type(field, false)?
        ));
    }
    for declaration in &message.oneof_decl {
        let proto_name = declaration.name.as_deref().unwrap_or("choice");
        output.push_str(&format!(
            "\t{}: {}_{},\n",
            odin_identifier(proto_name),
            message_type,
            pascal_identifier(proto_name)
        ));
    }
    output.push_str("}\n\n");
    Ok(())
}

fn expected_wire_type(field_type: Type) -> u8 {
    match field_type {
        Type::Fixed64 | Type::Sfixed64 | Type::Double => 1,
        Type::String | Type::Bytes | Type::Message => 2,
        Type::Fixed32 | Type::Sfixed32 | Type::Float => 5,
        _ => 0,
    }
}

fn is_packable(field_type: Type) -> bool {
    !matches!(
        field_type,
        Type::String | Type::Bytes | Type::Message | Type::Group
    )
}

fn read_value_lines(field: &FieldDescriptorProto, variable: &str, indent: &str) -> Result<String> {
    let mut lines = String::new();
    match field.r#type() {
        Type::String => {
            lines.push_str(&format!(
                "{indent}raw, value_ok := protobuf.read_bytes(&decoder)\n"
            ));
            lines.push_str(&format!("{indent}if !value_ok {{ return false }}\n"));
            lines.push_str(&format!("{indent}{variable} = string(raw)\n"));
        }
        Type::Bytes => {
            lines.push_str(&format!(
                "{indent}raw, value_ok := protobuf.read_bytes(&decoder)\n"
            ));
            lines.push_str(&format!("{indent}if !value_ok {{ return false }}\n"));
            lines.push_str(&format!("{indent}{variable} = raw\n"));
        }
        Type::Message => {
            let nested_type = field_base_type(field)?;
            lines.push_str(&format!(
                "{indent}raw, value_ok := protobuf.read_bytes(&decoder)\n"
            ));
            lines.push_str(&format!("{indent}if !value_ok {{ return false }}\n"));
            lines.push_str(&format!("{indent}nested := new({nested_type})\n"));
            lines.push_str(&format!(
                "{indent}if !decode_{nested_type}(raw, nested) {{ return false }}\n"
            ));
            lines.push_str(&format!("{indent}{variable} = nested\n"));
        }
        Type::Fixed32 => read_fixed_lines(&mut lines, variable, indent, "u32", "read_fixed32"),
        Type::Sfixed32 => read_fixed_lines(&mut lines, variable, indent, "i32", "read_fixed32"),
        Type::Float => read_fixed_lines(&mut lines, variable, indent, "f32", "read_float32"),
        Type::Fixed64 => read_fixed_lines(&mut lines, variable, indent, "u64", "read_fixed64"),
        Type::Sfixed64 => read_fixed_lines(&mut lines, variable, indent, "i64", "read_fixed64"),
        Type::Double => read_fixed_lines(&mut lines, variable, indent, "f64", "read_float64"),
        field_type => {
            lines.push_str(&format!(
                "{indent}raw, value_ok := protobuf.read_varint(&decoder)\n"
            ));
            lines.push_str(&format!("{indent}if !value_ok {{ return false }}\n"));
            let expression = match field_type {
                Type::Bool => "raw != 0".to_owned(),
                Type::Sint32 => "protobuf.decode_zigzag32(raw)".to_owned(),
                Type::Sint64 => "protobuf.decode_zigzag64(raw)".to_owned(),
                Type::Int32 => "i32(raw)".to_owned(),
                Type::Int64 => "i64(raw)".to_owned(),
                Type::Uint32 => "u32(raw)".to_owned(),
                Type::Uint64 => "raw".to_owned(),
                Type::Enum => format!("{}(raw)", field_base_type(field)?),
                _ => bail!("unsupported varint type {field_type:?}"),
            };
            lines.push_str(&format!("{indent}{variable} = {expression}\n"));
        }
    }
    Ok(lines)
}

fn read_fixed_lines(
    lines: &mut String,
    variable: &str,
    indent: &str,
    cast_type: &str,
    reader: &str,
) {
    lines.push_str(&format!(
        "{indent}raw, value_ok := protobuf.{reader}(&decoder)\n"
    ));
    lines.push_str(&format!("{indent}if !value_ok {{ return false }}\n"));
    lines.push_str(&format!("{indent}{variable} = {cast_type}(raw)\n"));
}

fn emit_decoder(
    output: &mut String,
    full_name: &str,
    message: &DescriptorProto,
    _schema: &Schema,
) -> Result<()> {
    let message_type = odin_type_name(full_name);
    output.push_str(&format!(
        "decode_{message_type} :: proc(data: []u8, value: ^{message_type}) -> bool {{\n"
    ));
    output.push_str("\tdecoder := protobuf.decoder(data)\n");
    output.push_str("\tfor protobuf.has_more(&decoder) {\n");
    output.push_str("\t\tfield_number, wire_type, key_ok := protobuf.read_key(&decoder)\n");
    output.push_str("\t\tif !key_ok { return false }\n");
    output.push_str("\t\tswitch field_number {\n");
    for field in &message.field {
        let number = field.number.context("field has no number")?;
        let expected_wire = expected_wire_type(field.r#type());
        let field_name = odin_identifier(field.name.as_deref().unwrap_or("field"));
        output.push_str(&format!("\t\tcase {number}:\n"));

        if field.label() == Label::Repeated
            && is_packable(field.r#type())
            && field.oneof_index.is_none()
        {
            output.push_str("\t\t\tif wire_type == 2 {\n");
            output.push_str("\t\t\t\tpacked, packed_ok := protobuf.read_bytes(&decoder)\n");
            output.push_str("\t\t\t\tif !packed_ok { return false }\n");
            output.push_str("\t\t\t\tpacked_decoder := decoder\n");
            output.push_str("\t\t\t\tdecoder = protobuf.decoder(packed)\n");
            let temp_type = field_base_type(field)?;
            output.push_str(&format!(
                "\t\t\t\tfor protobuf.has_more(&decoder) {{\n\t\t\t\t\ttemp: {temp_type}\n"
            ));
            output.push_str(&read_value_lines(field, "temp", "\t\t\t\t\t")?);
            output.push_str(&format!("\t\t\t\t\tappend(&value.{field_name}, temp)\n"));
            output.push_str("\t\t\t\t}\n");
            output.push_str("\t\t\t\tpacked_values_ok := decoder.ok\n");
            output.push_str("\t\t\t\tdecoder = packed_decoder\n");
            output.push_str("\t\t\t\tif !packed_values_ok { return false }\n");
            output.push_str(&format!(
                "\t\t\t}} else if wire_type == {expected_wire} {{\n"
            ));
            let temp_type = field_base_type(field)?;
            output.push_str(&format!("\t\t\t\ttemp: {temp_type}\n"));
            output.push_str(&read_value_lines(field, "temp", "\t\t\t\t")?);
            output.push_str(&format!("\t\t\t\tappend(&value.{field_name}, temp)\n"));
            output.push_str(
                "\t\t\t} else if !protobuf.skip_value(&decoder, wire_type) { return false }\n",
            );
            continue;
        }

        output.push_str(&format!(
            "\t\t\tif wire_type != {expected_wire} {{\n\t\t\t\tif !protobuf.skip_value(&decoder, wire_type) {{ return false }}\n\t\t\t\tcontinue\n\t\t\t}}\n"
        ));

        if let Some(oneof_index) = field.oneof_index {
            let declaration = &message.oneof_decl[oneof_index as usize];
            let union_name = format!(
                "{message_type}_{}",
                pascal_identifier(declaration.name.as_deref().unwrap_or("Choice"))
            );
            let wrapper = format!(
                "{union_name}_{}",
                pascal_identifier(field.name.as_deref().unwrap_or("Value"))
            );
            let storage_type = field_storage_type(field, true)?;
            output.push_str(&format!("\t\t\ttemp: {storage_type}\n"));
            output.push_str(&read_value_lines(field, "temp", "\t\t\t")?);
            let oneof_field = odin_identifier(declaration.name.as_deref().unwrap_or("choice"));
            output.push_str(&format!(
                "\t\t\tvalue.{oneof_field} = {wrapper}{{value = temp}}\n"
            ));
        } else if field.label() == Label::Repeated {
            if field.r#type() == Type::Message {
                let base = field_base_type(field)?;
                output.push_str(&format!("\t\t\ttemp_ptr: ^{base}\n"));
                output.push_str(&read_value_lines(field, "temp_ptr", "\t\t\t")?);
                output.push_str(&format!("\t\t\tappend(&value.{field_name}, temp_ptr^)\n"));
            } else {
                let base = field_base_type(field)?;
                output.push_str(&format!("\t\t\ttemp: {base}\n"));
                output.push_str(&read_value_lines(field, "temp", "\t\t\t")?);
                output.push_str(&format!("\t\t\tappend(&value.{field_name}, temp)\n"));
            }
        } else {
            output.push_str(&read_value_lines(
                field,
                &format!("value.{field_name}"),
                "\t\t\t",
            )?);
        }
    }
    output.push_str("\t\tcase:\n");
    output.push_str("\t\t\tif !protobuf.skip_value(&decoder, wire_type) { return false }\n");
    output.push_str("\t\t}\n\t}\n\treturn decoder.ok\n}\n\n");
    Ok(())
}

fn emit_encoder(
    output: &mut String,
    full_name: &str,
    message: &DescriptorProto,
    _schema: &Schema,
) -> Result<()> {
    let message_type = odin_type_name(full_name);
    output.push_str(&format!(
        "encode_{message_type} :: proc(value: ^{message_type}) -> [dynamic]u8 {{\n"
    ));
    output.push_str("\tresult := make([dynamic]u8)\n");
    for field in message
        .field
        .iter()
        .filter(|field| field.oneof_index.is_none())
    {
        let field_name = odin_identifier(field.name.as_deref().unwrap_or("field"));
        if field.label() == Label::Repeated {
            output.push_str(&format!("\tfor index in 0..<len(value.{field_name}) {{\n"));
            emit_encode_value(
                output,
                field,
                &format!("value.{field_name}[index]"),
                "\t\t",
                false,
            )?;
            output.push_str("\t}\n");
        } else {
            emit_encode_value(output, field, &format!("value.{field_name}"), "\t", true)?;
        }
    }
    for (oneof_index, declaration) in message.oneof_decl.iter().enumerate() {
        let oneof_field = odin_identifier(declaration.name.as_deref().unwrap_or("choice"));
        output.push_str(&format!(
            "\t#partial switch variant in value.{oneof_field} {{\n"
        ));
        for field in oneof_fields(message, oneof_index) {
            let wrapper = format!(
                "{message_type}_{}_{}",
                pascal_identifier(declaration.name.as_deref().unwrap_or("Choice")),
                pascal_identifier(field.name.as_deref().unwrap_or("Value"))
            );
            output.push_str(&format!("\tcase {wrapper}:\n"));
            emit_encode_value(output, field, "variant.value", "\t\t", false)?;
        }
        output.push_str("\t}\n");
    }
    output.push_str("\treturn result\n}\n\n");
    Ok(())
}

fn emit_encode_value(
    output: &mut String,
    field: &FieldDescriptorProto,
    expression: &str,
    indent: &str,
    omit_default: bool,
) -> Result<()> {
    let number = field.number.context("field has no number")?;
    let field_type = field.r#type();
    let condition = if !omit_default {
        None
    } else {
        Some(match field_type {
            Type::String | Type::Bytes => format!("len({expression}) > 0"),
            Type::Message => format!("{expression} != nil"),
            Type::Bool => expression.to_owned(),
            Type::Enum => format!("i32({expression}) != 0"),
            _ => format!("{expression} != 0"),
        })
    };
    let body_indent = if let Some(condition) = &condition {
        output.push_str(&format!("{indent}if {condition} {{\n"));
        format!("{indent}\t")
    } else {
        indent.to_owned()
    };

    match field_type {
        Type::String => output.push_str(&format!(
            "{body_indent}protobuf.append_string_field(&result, {number}, {expression})\n"
        )),
        Type::Bytes => output.push_str(&format!(
            "{body_indent}protobuf.append_bytes_field(&result, {number}, {expression})\n"
        )),
        Type::Message => {
            let nested_type = field_base_type(field)?;
            let pointer_expression = if field.label() == Label::Repeated {
                format!("&{expression}")
            } else {
                expression.to_owned()
            };
            output.push_str(&format!(
                "{body_indent}nested := encode_{nested_type}({pointer_expression})\n"
            ));
            output.push_str(&format!(
                "{body_indent}protobuf.append_bytes_field(&result, {number}, nested[:])\n"
            ));
            output.push_str(&format!("{body_indent}delete(nested)\n"));
        }
        Type::Fixed32 => emit_fixed_encode(output, number, expression, &body_indent, "append_fixed32_field", "u32"),
        Type::Sfixed32 => emit_fixed_encode(output, number, expression, &body_indent, "append_fixed32_field", "u32"),
        Type::Float => emit_fixed_encode(output, number, expression, &body_indent, "append_float32_field", "f32"),
        Type::Fixed64 => emit_fixed_encode(output, number, expression, &body_indent, "append_fixed64_field", "u64"),
        Type::Sfixed64 => emit_fixed_encode(output, number, expression, &body_indent, "append_fixed64_field", "u64"),
        Type::Double => emit_fixed_encode(output, number, expression, &body_indent, "append_float64_field", "f64"),
        Type::Bool => output.push_str(&format!(
            "{body_indent}protobuf.append_varint_field(&result, {number}, u64({expression}))\n"
        )),
        Type::Sint32 => output.push_str(&format!(
            "{body_indent}protobuf.append_varint_field(&result, {number}, protobuf.encode_zigzag32({expression}))\n"
        )),
        Type::Sint64 => output.push_str(&format!(
            "{body_indent}protobuf.append_varint_field(&result, {number}, protobuf.encode_zigzag64({expression}))\n"
        )),
        Type::Int32 => output.push_str(&format!(
            "{body_indent}protobuf.append_varint_field(&result, {number}, u64(i64({expression})))\n"
        )),
        Type::Int64 => output.push_str(&format!(
            "{body_indent}protobuf.append_varint_field(&result, {number}, u64({expression}))\n"
        )),
        Type::Uint32 | Type::Uint64 => output.push_str(&format!(
            "{body_indent}protobuf.append_varint_field(&result, {number}, u64({expression}))\n"
        )),
        Type::Enum => output.push_str(&format!(
            "{body_indent}protobuf.append_varint_field(&result, {number}, u64(i64({expression})))\n"
        )),
        Type::Group => bail!("groups are unsupported"),
    }
    if condition.is_some() {
        output.push_str(&format!("{indent}}}\n"));
    }
    Ok(())
}

fn emit_fixed_encode(
    output: &mut String,
    number: i32,
    expression: &str,
    indent: &str,
    function: &str,
    cast: &str,
) {
    output.push_str(&format!(
        "{indent}protobuf.{function}(&result, {number}, {cast}({expression}))\n"
    ));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn identifiers_are_stable_and_odin_safe() {
        assert_eq!(
            odin_type_name("coresdk.activity_task.ActivityTask"),
            "Coresdk_Activity_Task_ActivityTask"
        );
        assert_eq!(odin_identifier("context"), "context_");
        assert_eq!(odin_identifier("field-name"), "field_name");
        assert_eq!(
            pascal_identifier("will_complete_async"),
            "Will_Complete_Async"
        );
    }

    #[test]
    fn reachable_messages_follow_imported_type_names() {
        let child = DescriptorProto {
            name: Some("Child".to_owned()),
            ..Default::default()
        };
        let root = DescriptorProto {
            name: Some("Root".to_owned()),
            field: vec![FieldDescriptorProto {
                name: Some("child".to_owned()),
                number: Some(1),
                label: Some(Label::Optional as i32),
                r#type: Some(Type::Message as i32),
                type_name: Some(".imported.Child".to_owned()),
                ..Default::default()
            }],
            ..Default::default()
        };
        let mut schema = Schema::default();
        schema
            .messages
            .insert("local.Root".to_owned(), MessageInfo { descriptor: root });
        schema.messages.insert(
            "imported.Child".to_owned(),
            MessageInfo { descriptor: child },
        );

        let reachable = reachable_messages(&schema, &["local.Root".to_owned()]).unwrap();
        assert_eq!(
            reachable,
            BTreeSet::from(["imported.Child".to_owned(), "local.Root".to_owned()])
        );
    }

    #[test]
    fn oneof_generation_keeps_an_explicit_discriminator() {
        let message = DescriptorProto {
            name: Some("Envelope".to_owned()),
            oneof_decl: vec![prost_descriptor_types::OneofDescriptorProto {
                name: Some("value".to_owned()),
                ..Default::default()
            }],
            field: vec![FieldDescriptorProto {
                name: Some("text".to_owned()),
                number: Some(1),
                label: Some(Label::Optional as i32),
                r#type: Some(Type::String as i32),
                oneof_index: Some(0),
                ..Default::default()
            }],
            ..Default::default()
        };
        let mut output = String::new();
        emit_oneof_types(
            &mut output,
            "example.Envelope",
            &message,
            &Schema::default(),
        )
        .unwrap();
        emit_message_type(
            &mut output,
            "example.Envelope",
            &message,
            &Schema::default(),
        )
        .unwrap();

        assert!(output.contains("Example_Envelope_Value_Text :: struct { value: string }"));
        assert!(output.contains("Example_Envelope_Value :: union"));
        assert!(output.contains("value: Example_Envelope_Value"));
    }
}
